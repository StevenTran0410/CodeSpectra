"""Result-store repository — plain async functions, no ORM, no class wrapper.

Deliberate deviation from backend/domain/*/service.py's class-based (XService)
convention — CS-261 explicitly mandates "thin repository module, plain functions".
"""
from __future__ import annotations

import json
import uuid
from datetime import UTC, datetime
from typing import Literal

from agent_eval_harness.instrumentation.base import CapturedSpan
from agent_eval_harness.store.database import get_db


def new_id() -> str:
    return str(uuid.uuid4())


def utc_now_iso() -> str:
    return datetime.now(UTC).isoformat()


async def insert_run(target_system_id: str, eval_plan_id: str | None = None) -> str:
    run_id = new_id()
    db = get_db()
    await db.execute(
        "INSERT INTO runs (id, target_system_id, eval_plan_id, started_at, status) "
        "VALUES (?, ?, ?, ?, 'running')",
        (run_id, target_system_id, eval_plan_id, utc_now_iso()),
    )
    await db.commit()
    return run_id


async def finish_run(run_id: str, status: Literal["completed", "failed"]) -> None:
    db = get_db()
    await db.execute(
        "UPDATE runs SET status = ?, finished_at = ? WHERE id = ?",
        (status, utc_now_iso(), run_id),
    )
    await db.commit()


async def insert_trace(
    run_id: str, root_input: str, dataset_case_id: str | None = None
) -> str:
    trace_id = new_id()
    db = get_db()
    await db.execute(
        "INSERT INTO traces (id, run_id, dataset_case_id, root_input) VALUES (?, ?, ?, ?)",
        (trace_id, run_id, dataset_case_id, root_input),
    )
    await db.commit()
    return trace_id


async def finalize_trace(
    trace_id: str, final_output: str, total_tokens: int, total_latency_ms: int
) -> None:
    db = get_db()
    await db.execute(
        "UPDATE traces SET final_output = ?, total_tokens = ?, total_latency_ms = ? WHERE id = ?",
        (final_output, total_tokens, total_latency_ms, trace_id),
    )
    await db.commit()


async def insert_spans_bulk(trace_id: str, spans: list[CapturedSpan]) -> None:
    """One transaction, executemany — span_id is generated by the tracer, kept as-is
    (uuid4, stable across the whole capture lifetime)."""
    db = get_db()
    rows = [
        (
            span.span_id,
            trace_id,
            span.parent_span_id,
            span.component_id,
            span.span_type,
            span.input_json,
            span.output_json,
            span.model,
            span.tokens_in,
            span.tokens_out,
            span.latency_ms,
            span.started_at,
            json.dumps(
                {
                    "tier": span.tier,
                    "token_source": span.token_source,
                    "raw_tags": span.tags,
                }
            ),
        )
        for span in spans
    ]
    await db.executemany(
        "INSERT INTO spans (id, trace_id, parent_span_id, component_id, span_type, "
        "input_json, output_json, model, tokens_in, tokens_out, latency_ms, started_at, "
        "details_json) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
        rows,
    )
    await db.commit()


async def get_run(run_id: str) -> dict | None:
    db = get_db()
    async with db.execute("SELECT * FROM runs WHERE id = ?", (run_id,)) as cur:
        row = await cur.fetchone()
    return dict(row) if row else None


async def get_traces_for_run(run_id: str) -> list[dict]:
    db = get_db()
    async with db.execute("SELECT * FROM traces WHERE run_id = ?", (run_id,)) as cur:
        rows = await cur.fetchall()
    return [dict(row) for row in rows]


async def get_spans_for_trace(trace_id: str) -> list[dict]:
    db = get_db()
    async with db.execute(
        "SELECT * FROM spans WHERE trace_id = ? ORDER BY started_at", (trace_id,)
    ) as cur:
        rows = await cur.fetchall()
    return [dict(row) for row in rows]


async def get_span_tree(trace_id: str) -> list[dict]:
    """Returns flat span dicts (parent_span_id-linked) — caller builds the tree.
    Kept flat here (not a nested structure) so callers (CLI printer today, UI later)
    can build whatever shape they need from the same rows."""
    return await get_spans_for_trace(trace_id)


async def count_unmatched_spans(trace_id: str) -> int:
    db = get_db()
    async with db.execute(
        "SELECT COUNT(*) as n FROM spans WHERE trace_id = ? AND component_id IS NULL",
        (trace_id,),
    ) as cur:
        row = await cur.fetchone()
    return row["n"] if row else 0
