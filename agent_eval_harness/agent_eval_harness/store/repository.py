async def insert_spans_bulk(trace_id: str, spans: list[CapturedSpan]) -> None:
    """One transaction, executemany — span_id is generated by the tracer, kept as-is
    (uuid4, stable across the whole capture lifetime)."""
    db = get_db()
    rows = [
        (
            span.span_id,
            trace_id,
            span.parent_span_id,
            span.component_id,
            span.span_type,
            span.input_json,
            span.output_json,
            span.model,
            span.tokens_in,
            span.tokens_out,
            span.latency_ms,
            span.started_at,
            json.dumps(
                {
                    "tier": span.tier,
                    "token_source": span.token_source,
                    "raw_tags": span.tags,
                }
            ),
        )
        for span in spans
    ]
    await db.executemany(
        "INSERT INTO spans (id, trace_id, parent_span_id, component_id, span_type, "
        "input_json, output_json, model, tokens_in, tokens_out, latency_ms, started_at, "
        "details_json) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
        rows,
    )
    await db.commit()


async def get_run(run_id: str) -> dict | None:
    db = get_db()
