"""Result-store repository — plain async functions, no ORM, no class wrapper.

Deliberate deviation from backend/domain/*/service.py's class-based (XService)
convention — CS-261 explicitly mandates "thin repository module, plain functions".
"""
from __future__ import annotations

import json
import uuid
from typing import Literal

from agent_eval_harness.instrumentation._extract import utc_now_iso
from agent_eval_harness.instrumentation.base import CapturedSpan
